"""Generate matching firmware and browser pixel faces from one design file."""
from pathlib import Path
import json
import re

ROOT = Path(__file__).resolve().parent.parent


def main():
    data = json.loads((ROOT/'expressions/claude_pixel.json').read_text())
    faces, accents = data['faces'], data['accents']
    assert data['grid'] == dict(width=6, height=7, cell=10)
    def bits(rows):
        return '{' + ','.join(str(int(row, 2)) for row in rows) + '}'
    def rgb565(color):
        value = int(color[1:], 16)
        return ((value >> 16 & 248) << 8) | ((value >> 8 & 252) << 3) | ((value & 255) >> 3)
    poses, presets, extras = [], [], []
    for name, face in faces.items():
        for eye in ('left','right'):
            assert len(face[eye]) == 7 and all(len(row)==6 and set(row)<=set('01') for row in face[eye])
        screen = face['screen']
        assert screen['bg']=='#000000' and screen['mouth']=='none' and not screen['shake']
        poses.append('{"%s",%s,%s,%s}' % (name,bits(face['left']),bits(face['right']),str(face['blink']).lower()))
        presets.append('{"%s","%s","%s","%s"}' % (name,screen['fg'],screen['anim'],screen['extra']))
    for name, accent in accents.items():
        rows=accent['rows'];width=len(rows[0])
        assert len(rows)<=7 and width<=9 and all(len(row)==width and set(row)<=set('01') for row in rows)
        extras.append('{"%s",%d,%d,%d,%s,%d,%s}' % (name,width,len(rows),accent['cell'],bits(rows),rgb565(accent.get('color','#000000')),str('color' in accent).lower()))
    header='''// Generated by tools/build_claude_faces.py; edit expressions/claude_pixel.json.
#pragma once
struct ClaudePose { const char* name; uint8_t left[7], right[7]; bool blink; };
struct ClaudeScreenPreset { const char* name; const char* fg; const char* anim; const char* extra; };
struct ClaudeAccent { const char* name; uint8_t width,height,cell; uint16_t rows[7],color; bool ownColor; };
static const ClaudePose CLAUDE_POSES[] = {__POSES__};
static const ClaudeScreenPreset CLAUDE_SCREENS[] = {__PRESETS__};
static const ClaudeAccent CLAUDE_ACCENTS[] = {__ACCENTS__};
static void drawClaudeEyes(GFXcanvas16& c,const String& pose,const String& anim,uint16_t fg,float t) {
  const ClaudePose* p=&CLAUDE_POSES[0];
  for(const auto& candidate:CLAUDE_POSES) if(pose==candidate.name) { p=&candidate; break; }
  int dx=0,dy=0;
  if(anim=="look") { dx=(int)(sinf(t*.7f)*6-2); dy=-6; }
  else if(anim=="scan") { dx=(int)(sinf(t*2.4f)*8); dy=3; }
  else if(anim=="down") dy=5;
  else if(anim=="bounce") dy=(int)(-fabsf(sinf(t*1.7f))*5);
  bool blink=p->blink && fmodf(t+1.3f,3.6f)<.12f;
  for(int eye=0;eye<2;eye++) {
    int x=(eye?178:62)+dx,y=120+dy;
    if(blink) { c.fillRect(x-10,y-1,20,3,fg); continue; }
    const uint8_t* rows=eye?p->right:p->left;
    for(int row=0;row<7;row++) for(int col=0;col<6;col++)
      if(rows[row] & (1 << (5-col))) c.fillRect(x-30+col*10,y-35+row*10,10,10,fg);
  }
}
static void drawClaudeAccent(GFXcanvas16& c,const String& name,uint16_t fg) {
  for(const auto& a:CLAUDE_ACCENTS) if(name==a.name) {
    int x=120-a.width*a.cell/2;
    for(int row=0;row<a.height;row++) for(int col=0;col<a.width;col++)
      if(a.rows[row] & (1 << (a.width-1-col))) c.fillRect(x+col*a.cell,183+row*a.cell,a.cell,a.cell,a.ownColor?a.color:fg);
    return;
  }
}
'''.replace('__POSES__',',\n'.join(poses)).replace('__PRESETS__',',\n'.join(presets)).replace('__ACCENTS__',',\n'.join(extras))
    (ROOT/'firmware/src/claude_faces.generated.h').write_text(header)
    js='''// Generated by tools/build_claude_faces.py; one source for device and preview.
const CLAUDE_FACES=__DATA__;
const CLAUDE_SCREENS=Object.fromEntries(Object.entries(CLAUDE_FACES.faces).map(([name,face])=>[name,face.screen]));
function drawClaudeEyes(ctx,p,t) {
  const face=CLAUDE_FACES.faces[p.pose]||CLAUDE_FACES.faces.idle;
  let dx=0,dy=0;
  if(p.anim==='look') { dx=Math.trunc(Math.sin(t*.7)*6-2); dy=-6; }
  else if(p.anim==='scan') { dx=Math.trunc(Math.sin(t*2.4)*8); dy=3; }
  else if(p.anim==='down') dy=5;
  else if(p.anim==='bounce') dy=Math.trunc(-Math.abs(Math.sin(t*1.7))*5);
  const blink=face.blink && ((t+1.3)%3.6)<.12;
  ctx.fillStyle=p.fg;
  [face.left,face.right].forEach((rows,i)=>{
    const x=(i?178:62)+dx,y=120+dy;
    if(blink) { ctx.fillRect(x-10,y-1,20,3); return; }
    rows.forEach((row,iy)=>Array.from(row).forEach((bit,ix)=>{
      if(bit==='1') ctx.fillRect(x-30+ix*10,y-35+iy*10,10,10);
    }));
  });
}
function drawClaudeAccent(ctx,p) {
  const a=CLAUDE_FACES.accents[p.extra];if(!a)return;
  const width=a.rows[0].length,x=120-Math.floor(width*a.cell/2);
  ctx.fillStyle=a.color||p.fg;
  a.rows.forEach((row,iy)=>Array.from(row).forEach((bit,ix)=>{
    if(bit==='1')ctx.fillRect(x+ix*a.cell,183+iy*a.cell,a.cell,a.cell);
  }));
}
function drawClaudeFace(ctx,p,t) {
  ctx.fillStyle=p.bg;ctx.fillRect(0,0,240,240);
  drawClaudeEyes(ctx,p,t);drawClaudeAccent(ctx,p);
}
'''.replace('__DATA__',json.dumps(data,ensure_ascii=False,separators=(',',':')))
    (ROOT/'bridge/claude_faces.js').write_text(js)
    for name in ('bridge/webui.html','simulator/index.html'):
        path=ROOT/name;html=path.read_text()
        library='<script id="claudeFaceLibrary">\n'+js+'</script>'
        pattern=r'<script id="claudeFaceLibrary">.*?</script>'
        if re.search(pattern,html,re.S):
            html=re.sub(pattern,lambda _:library,html,flags=re.S)
        else:
            html=html.replace('<script>',library+'\n<script>',1)
        path.write_text(html)
    print(f'Generated {len(faces)} matching pixel faces and {len(accents)} accents.')


if __name__=='__main__':
    main()
